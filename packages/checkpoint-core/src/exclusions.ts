/**
 * Build the content for `.git/info/exclude`, merging built-in
 * patterns with any LFS patterns found in the workspace.
 *
 * @param extraPatterns  - LFS patterns from .gitattributes
 * @param userExcludes   - patterns from user repo's .git/info/exclude
 */
export function buildExcludeContent(
  extraPatterns: string[] = [],
  userExcludes: string[] = [],
): string {
  const lines = [
    '# Auto-generated by TabTin Checkpoint — do not edit',
    '',
    ...CHECKPOINT_EXCLUDE_PATTERNS,
  ]
  if (extraPatterns.length > 0) {
    lines.push('', '# LFS patterns', ...extraPatterns)
  }
  if (userExcludes.length > 0) {
    lines.push('', '# User repo .git/info/exclude', ...userExcludes)
  }
  lines.push('')
  return lines.join('\n') + '\n'
}
