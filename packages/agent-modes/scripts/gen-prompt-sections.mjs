#!/usr/bin/env node
/**
 * 从 src/agent-modes/prompts/*.md 生成 prompt-content.generated.ts。
 *
 * SSoT 是 .md 文件——修改 prompt 只需编辑 .md，然后 build 自动重新生成 TS 常量。
 * Django 端未来可以直接读同一份 .md（路径在 contract JSON 里声明）。
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const PROMPTS_DIR = resolve(__dirname, '../src/prompts');
const OUTPUT = resolve(__dirname, '../src/prompt-content.generated.ts');

const MODES = ['plan', 'ask', 'study', 'group'];

/** Per-turn sparse reminder 内容（Phase 2）。 */
const SPARSE_MODES = [
  { file: 'ask-sparse', constName: 'PROMPT_ASK_SPARSE' },
  { file: 'plan-sparse', constName: 'PROMPT_PLAN_SPARSE' },
  { file: 'study-sparse', constName: 'PROMPT_STUDY_SPARSE' },
];

/** Phase 3：用户批准 switch_mode 后一次性注入（plan mode 退出提示）。 */
const MODE_TRANSITION_REMINDER = { file: 'mode-transition-reminder', constName: 'PROMPT_MODE_TRANSITION_REMINDER' };

function escapeForTemplateLiteral(s) {
  return s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
}

const lines = [
  '/* eslint-disable */',
  '// AUTO-GENERATED by scripts/gen-prompt-sections.mjs — DO NOT EDIT',
  '// SSoT: src/agent-modes/prompts/*.md',
  '',
];

for (const mode of MODES) {
  const path = resolve(PROMPTS_DIR, `${mode}.md`);
  const raw = readFileSync(path, 'utf-8');
  const escaped = escapeForTemplateLiteral(raw);
  const constName = `PROMPT_${mode.toUpperCase()}`;
  lines.push(`export const ${constName} = \`${escaped}\`;`);
  lines.push('');
}

for (const { file, constName } of SPARSE_MODES) {
  const path = resolve(PROMPTS_DIR, `${file}.md`);
  const raw = readFileSync(path, 'utf-8');
  const escaped = escapeForTemplateLiteral(raw);
  lines.push(`export const ${constName} = \`${escaped}\`;`);
  lines.push('');
}

{
  const path = resolve(PROMPTS_DIR, `${MODE_TRANSITION_REMINDER.file}.md`);
  const raw = readFileSync(path, 'utf-8');
  const escaped = escapeForTemplateLiteral(raw);
  lines.push(`export const ${MODE_TRANSITION_REMINDER.constName} = \`${escaped}\`;`);
  lines.push('');
}

writeFileSync(OUTPUT, lines.join('\n'), 'utf-8');
console.log(`✓ Generated ${OUTPUT}`);
