let okCount = 0;
let failCount = 0;
for (const job of jobs) {
  if (!existsSync(job.src)) {
    console.error(`  ✘ ${job.name}: 源目录不存在 ${job.src}（先跑相应 codegen step）`);
    failCount++;
    continue;
  }

  // 清空目标目录（保留 .git 等）；然后 cp
  const handwrittenAllowList = job.name.includes('(Swift)')
    ? HANDWRITTEN_FILES_SWIFT
    : job.name.includes('(Kotlin)')
      ? HANDWRITTEN_FILES_KOTLIN
      : new Set<string>();
  const savedHandwritten = preserveHandwrittenFiles(job.dest, handwrittenAllowList);
  if (existsSync(job.dest)) {
    rmSync(job.dest, { recursive: true });
  }
  mkdirSync(job.dest, { recursive: true });

  // 拷贝所有文件
  const entries = readdirSync(job.src);
  let fileCount = 0;
  for (const entry of entries) {
    const srcPath = resolve(job.src, entry);
    const destPath = resolve(job.dest, entry);
    cpSync(srcPath, destPath, { recursive: true });
    if (statSync(srcPath).isFile()) fileCount++;
  }

  restoreHandwrittenFiles(job.dest, savedHandwritten);
  fileCount += savedHandwritten.size;

  // 写 README
  writeFileSync(resolve(job.dest, job.readmeName), job.readme);

  console.log(`  ✔ ${job.name}: ${fileCount} 文件 → ${job.dest}`);
  okCount++;
}

console.log(`\n[07_vendor_in] 完成：${okCount} ok, ${failCount} fail`);
if (failCount > 0) process.exit(1);

function preserveHandwrittenFiles(
  dest: string,
  allowList: ReadonlySet<string>,
): Map<string, string> {
  const saved = new Map<string, string>();
  if (!existsSync(dest)) return saved;
  for (const name of allowList) {
    const path = resolve(dest, name);
    if (existsSync(path) && statSync(path).isFile()) {
      saved.set(name, readFileSync(path, 'utf-8'));
    }
  }
  return saved;
}

function restoreHandwrittenFiles(dest: string, saved: Map<string, string>): void {
  for (const [name, contents] of saved) {
    writeFileSync(resolve(dest, name), contents);
  }
}
