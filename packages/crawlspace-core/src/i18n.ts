let currentLocale: CrawlspaceLocale = 'zh-CN';
let externalTranslator: Translator | null = null;

const formatMessage = (template: string, params?: MessageParams): string => {
  if (!params) return template;
  return template.replace(/\{\{\s*(\w+)\s*\}\}/g, (_, key) => {
    const value = params[key];
    return value === undefined || value === null ? '' : String(value);
  });
};

export const setCrawlspaceLocale = (locale: CrawlspaceLocale): void => {
  currentLocale = locale;
};

export const setCrawlspaceTranslator = (translator: Translator | null): void => {
  externalTranslator = translator;
};

export const getCrawlspaceLocale = (): CrawlspaceLocale => currentLocale;

export const t = (key: string, params?: MessageParams): string => {
  if (externalTranslator) {
    return externalTranslator(`crawlspace.${key}`, params);
  }
  const template =
    MESSAGES[currentLocale]?.[key] ??
    MESSAGES['en-US']?.[key] ??
    key;
  return formatMessage(template, params);
};
