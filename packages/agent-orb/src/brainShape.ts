/** 留边系数：脑轮廓顶到画布边缘会被裁，且贴边看着发闷 */
const BRAIN_FILL = 0.92;

export interface BrainTarget {
  x: number;
  y: number;
}

/** 把归一化脑点映射到边长 `size` 的逻辑画布坐标。 */
export function buildBrainTargets(size: number): BrainTarget[] {
  const c = size / 2;
  const k = (size / 2) * BRAIN_FILL;
  return BRAIN_NORMALIZED.map(([x, y]) => ({ x: c + x * k, y: c + y * k }));
}

export const BRAIN_POINT_COUNT = BRAIN_NORMALIZED.length;
