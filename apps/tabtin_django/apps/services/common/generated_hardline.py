class HardlineHit:
    """v3 端 HardlineHit —— 与 TS hardline-v3 的 HardlineHit 对齐。"""

    hit: bool
    pattern: Optional[str] = None
    description: Optional[str] = None


@dataclass(frozen=True)
class SensitivePathDecision:
    """v3 端 SensitivePathDecision —— 敏感路径四态判决结果。"""

    hit: bool
    action: str  # 'deny' | 'ask' | 'allow'
    category: Optional[str] = None
    description: Optional[str] = None
    pattern: Optional[str] = None


def _truncate(s: str, max_len: int = _MAX_MATCH_TEXT_LEN) -> str:
    if len(s) <= max_len:
        return s
    return s[:max_len] + "…"


def _extract_matchable_fields(tool_input: Any) -> List[Tuple[str, str]]:
    """镜像 TS extractMatchableFields —— 先扫 sensitive 字段，全无命中则 fallback 扫所有 string。"""
    out: List[Tuple[str, str]] = []
    if not isinstance(tool_input, dict):
        return out

    for field in SENSITIVE_FIELD_NAMES:
        raw = tool_input.get(field)
        if isinstance(raw, str) and len(raw) > 0:
            out.append((field, raw))

    if not out:
        for k, v in tool_input.items():
            if isinstance(v, str) and len(v) > 0:
                out.append((k, v))

    return out


def check_safety_hardline(
    tool_name: str, tool_input: Optional[dict]
) -> Optional[HardlineVerdict]:
    """v1 行为（PRD 05 §6.2 Layer 1）：检查 tool 调用是否触发硬底线。

    与 TS ``checkSafetyHardline`` 完全对齐。
    """
    fields = _extract_matchable_fields(tool_input)
    if not fields:
        return None

    for field, value in fields:
        for pattern, name in FORCE_BLOCK_PATTERNS:
            if pattern.search(value):
                return HardlineVerdict(
                    kind="block",
                    pattern_name=name,
                    matched_text=_truncate(value),
                    matched_field=field,
                )

    for field, value in fields:
        for pattern, name in FORCE_CONFIRM_PATTERNS:
            if pattern.search(value):
                return HardlineVerdict(
                    kind="confirm",
                    pattern_name=name,
                    matched_text=_truncate(value),
                    matched_field=field,
                )

    return None


def list_hardline_pattern_names() -> dict:
    """v1：列所有 pattern name（block / confirm 两组）。"""
    return {
        "block": [name for _, name in FORCE_BLOCK_PATTERNS],
        "confirm": [name for _, name in FORCE_CONFIRM_PATTERNS],
    }


