def check_hardline_command(command: Optional[str]) -> HardlineHit:
    """v3：绝对命令红线检查（与 TS checkHardlineCommand 对齐）。"""
    if not isinstance(command, str) or len(command) == 0:
        return HardlineHit(hit=False)
    for pattern, name, desc in ABSOLUTE_COMMAND_DENYLIST:
        if pattern.search(command):
            return HardlineHit(hit=True, pattern=name, description=desc)
    return HardlineHit(hit=False)


def check_hardline_path(path: Optional[str], kind: str) -> HardlineHit:
    """v3：绝对路径红线检查（与 TS checkHardlinePath 对齐）。

    ``kind`` 当前未参与匹配（与 TS 行为一致：仅做 pattern 扫描，
    "写"语义由调用方在 judge 中判断）。
    """
    _ = kind  # 与 TS 签名对齐
    if not isinstance(path, str) or len(path) == 0:
        return HardlineHit(hit=False)
    for pattern, name, desc in ABSOLUTE_PATH_DENYLIST:
        if pattern.search(path):
            return HardlineHit(hit=True, pattern=name, description=desc)
    return HardlineHit(hit=False)


def check_sensitive_path(
    path: Optional[str],
    kind: str,
    in_workspace: bool,
    is_write: bool,
) -> SensitivePathDecision:
    """v3：敏感路径四态判决（与 TS checkSensitivePath 对齐）。

    矩阵：
        |     | 工作区外 | 工作区内 |
        | 写  | deny    | ask     |
        | 读  | ask     | allow   |
    """
    _ = kind  # 与 TS 签名对齐
    if not isinstance(path, str) or len(path) == 0:
        return SensitivePathDecision(hit=False, action="allow")
    for pattern, name, category, desc in SENSITIVE_PATH_LIST:
        if pattern.search(path):
            if is_write:
                action = "ask" if in_workspace else "deny"
            else:
                action = "allow" if in_workspace else "ask"
            return SensitivePathDecision(
                hit=True,
                action=action,
                category=category,
                description=desc,
                pattern=name,
            )
    return SensitivePathDecision(hit=False, action="allow")


